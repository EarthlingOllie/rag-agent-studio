"""The Provider Credential table.

The secret is stored only sealed (``app.crypto.envelope``), bound to the credential's ID and
Organisation, so a sealed value copied onto another row fails to open. Provider, auth kind,
capabilities and check outcome are plain strings, so new providers need no enum migration.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, LargeBinary, String, UniqueConstraint
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base, IdMixin


class ProviderCredential(IdMixin, Base):
    __tablename__ = "provider_credentials"
    __table_args__ = (UniqueConstraint("organisation_id", "name"),)

    organisation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organisations.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(100))
    provider: Mapped[str] = mapped_column(String(32))
    auth_kind: Mapped[str] = mapped_column(String(32))
    # None for a Bedrock IAM role, which needs no secret: the platform assumes the role.
    secret_sealed: Mapped[bytes | None] = mapped_column(LargeBinary)
    # Only for providers that have regions (Bedrock).
    region: Mapped[str | None] = mapped_column(String(32))
    # The Owner's IAM role the platform assumes, for Bedrock role credentials. Not a secret.
    role_arn: Mapped[str | None] = mapped_column(String(2048))
    # The last characters of the secret (or of the AWS access key ID), which is all the API
    # ever shows of it. None when there is no secret (a Bedrock IAM role).
    masked_suffix: Mapped[str | None] = mapped_column(String(8))
    capabilities: Mapped[list[str]] = mapped_column(ARRAY(String(32)))
    # "passed" or "failed", with the typed reason when it failed.
    check_status: Mapped[str] = mapped_column(String(16))
    check_failure: Mapped[str | None] = mapped_column(String(32))
    last_checked_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # When the secret was last set: at creation, then at each rotation.
    secret_set_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))


class AwsExternalId(Base):
    """The Organisation's external ID: the shared value an Owner's IAM role trust policy
    requires before the platform may assume the role. Generated by the platform, stable, and
    unguessable, so another customer can't get the platform to assume this one's role."""

    __tablename__ = "aws_external_ids"

    organisation_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organisations.id", ondelete="CASCADE"), primary_key=True
    )
    external_id: Mapped[str] = mapped_column(String(64), unique=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
